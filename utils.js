/**
 * Sanitizes an untrusted string to prevent XSS.
 * @param {string} str 
 * @returns {string}
 */
export function sanitize(str) {
  if (typeof str !== 'string') return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;')
    .replace(/\//g, '&#x2F;');
}

/**
 * Generates a unique ID for transactions.
 * @returns {string}
 */
export function generateId() {
  if (typeof crypto !== 'undefined' && crypto.randomUUID) {
    return 'tx_' + crypto.randomUUID();
  }
  // Fallback for older browsers
  return 'tx_' + Math.random().toString(36).substring(2, 11) + Date.now().toString(36);
}

/**
 * Formats a numeric value into a localized currency string.
 * It respects custom currency symbols and formatting.
 * @param {number} amount 
 * @param {Object} settings - { currency, currencySymbol, startOfWeek, budget }
 * @returns {string}
 */
export function formatCurrency(amount, settings = {}) {
  const symbol = settings.currencySymbol || '₹';
  const formatter = new Intl.NumberFormat(navigator.language || 'en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  });
  
  // Clean alignment
  return `${symbol} ${formatter.format(amount)}`;
}

/**
 * Formats an ISO string date to YYYY-MM-DD.
 * @param {Date|string} date 
 * @returns {string}
 */
export function formatDateISO(date) {
  const d = new Date(date);
  if (isNaN(d.getTime())) return '';
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  const year = d.getFullYear();
  return `${year}-${month}-${day}`;
}

/**
 * Formats YYYY-MM-DD date string to local medium date format (e.g. "26 May 2026")
 * @param {string} dateStr 
 * @returns {string}
 */
export function formatDateFriendly(dateStr) {
  const parts = dateStr.split('-');
  if (parts.length !== 3) return dateStr;
  
  // Avoid local timezone shifts by parsing directly as local date
  const year = parseInt(parts[0], 10);
  const month = parseInt(parts[1], 10) - 1;
  const day = parseInt(parts[2], 10);
  const date = new Date(year, month, day);
  
  return date.toLocaleDateString(undefined, {
    day: 'numeric',
    month: 'short',
    year: 'numeric'
  });
}

/**
 * Formats YYYY-MM-DD date string to a relative label like "Today" or "Yesterday"
 * @param {string} dateStr 
 * @returns {string}
 */
export function getRelativeDayName(dateStr) {
  const today = formatDateISO(new Date());
  
  const yesterdayDate = new Date();
  yesterdayDate.setDate(yesterdayDate.getDate() - 1);
  const yesterday = formatDateISO(yesterdayDate);
  
  if (dateStr === today) {
    return 'Today';
  } else if (dateStr === yesterday) {
    return 'Yesterday';
  }
  
  return formatDateFriendly(dateStr);
}

